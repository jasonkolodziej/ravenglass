#!/usr/bin/env bash
# Local Dovecot IMAP server for the mail-imap integration tests (crates/mail-imap/tests/dovecot.rs),
# run unprivileged from a generated configuration. Dovecot itself comes from the system
# (`apt-get install dovecot-imapd`); nothing is downloaded.
#
#   tools/dovecot.sh start     generate a config and certificate in a temp dir and start Dovecot
#   tools/dovecot.sh stop      stop it and delete the temp dir
#   tools/dovecot.sh status    say whether it runs, and where
#   tools/dovecot.sh doveadm … run doveadm against the running instance (e.g. `save -u USER`)
#
# Ports (loopback only): 3144 IMAP with STARTTLS, 3994 IMAP over implicit TLS. Dovecot counts
# loopback as secure, so 3144 also takes a login without TLS; the command-recording tests use that.
# Accounts are passwd-files, one per user, in <dir>/users/ (file name = login, password
# "dovecot-test-password"); the tests write them. One file each, because Dovecot rereads a changed
# passwd-file at most once a second and would miss users added in quick succession. A user
# whose line carries `userdb_namespace/inbox/prefix=INBOX.` sees the
# Courier-style layout (`INBOX.` prefix, `.` separator); everyone else gets `/` and no prefix.
# SPECIAL-USE flags are configured on Drafts, Sent, Trash, Junk and Archive.
#
# Where things are: the temp dir's path is written to tools/.cache/dovecot.dir (gitignored);
# the test certificate is <dir>/cert.pem. The tests read both.
# Then: RAVENGLASS_DOVECOT_TEST=1 cargo test -p mail-imap --test dovecot
set -euo pipefail

TOOLS="$(cd "$(dirname "$0")" && pwd)"
CACHE="$TOOLS/.cache"
POINTER="$CACHE/dovecot.dir"
IMAP_PORT="${DOVECOT_IMAP_PORT:-3144}"
IMAPS_PORT="${DOVECOT_IMAPS_PORT:-3994}"

find_dovecot() {
    for candidate in "$(command -v dovecot || true)" /usr/sbin/dovecot /usr/local/sbin/dovecot; do
        if [ -n "$candidate" ] && [ -x "$candidate" ]; then echo "$candidate"; return; fi
    done
    echo "dovecot is not installed (apt-get install dovecot-imapd)" >&2
    exit 1
}

find_doveadm() {
    for candidate in "$(command -v doveadm || true)" /usr/bin/doveadm /usr/local/bin/doveadm; do
        if [ -n "$candidate" ] && [ -x "$candidate" ]; then echo "$candidate"; return; fi
    done
    echo "doveadm is not installed" >&2
    exit 1
}

current_dir() { [ -f "$POINTER" ] && cat "$POINTER"; }

running() {
    local dir
    dir="$(current_dir)" || return 1
    [ -f "$dir/run/master.pid" ] && kill -0 "$(cat "$dir/run/master.pid")" 2>/dev/null
}

configure() {
    local dir="$1" user group uid gid
    user="$(id -un)"; group="$(id -gn)"; uid="$(id -u)"; gid="$(id -g)"
    if [ "$uid" = 0 ]; then
        # Dovecot will not keep mail as root: when started by root, it serves as `nobody`.
        user=nobody; group="$(id -gn nobody)"; uid="$(id -u nobody)"; gid="$(id -g nobody)"
    fi
    mkdir -p "$dir/run" "$dir/state" "$dir/home"
    # A throwaway self-signed certificate for localhost, so the TLS tests can trust exactly it.
    openssl req -x509 -newkey ec -pkeyopt ec_paramgen_curve:prime256v1 -nodes -days 3650 \
        -subj "/CN=localhost" -addext "subjectAltName=DNS:localhost,IP:127.0.0.1" \
        -addext "basicConstraints=critical,CA:FALSE" -addext "extendedKeyUsage=serverAuth" \
        -keyout "$dir/key.pem" -out "$dir/cert.pem" >/dev/null 2>&1
    mkdir -p "$dir/users"
    chmod 755 "$dir" "$dir/users"
    chmod 644 "$dir/cert.pem"
    chown "$uid:$gid" "$dir/home" "$dir/key.pem"
    cat >"$dir/dovecot.conf" <<EOF
# Generated by tools/dovecot.sh; deleted by \`tools/dovecot.sh stop\`.
base_dir = $dir/run
state_dir = $dir/state
instance_name = ravenglass-test
log_path = $dir/dovecot.log
info_log_path = $dir/dovecot.log
protocols = imap
listen = 127.0.0.1

default_internal_user = $user
default_internal_group = $group
default_login_user = $user
mail_uid = $uid
mail_gid = $gid
first_valid_uid = $uid
last_valid_uid = $uid
first_valid_gid = $gid

ssl = yes
ssl_cert = <$dir/cert.pem
ssl_key = <$dir/key.pem
ssl_min_protocol = TLSv1.2
# Loopback counts as secure to Dovecot; a client that asks for STARTTLS still gets it.
disable_plaintext_auth = yes
auth_mechanisms = plain login
auth_verbose = no
mail_max_userip_connections = 100

passdb {
  driver = passwd-file
  args = scheme=PLAIN username_format=%u $dir/users/%u
}
userdb {
  driver = passwd-file
  args = username_format=%u $dir/users/%u
  default_fields = uid=$uid gid=$gid home=$dir/home/%u
}

mail_location = maildir:~/Maildir
mail_plugins =
imap_idle_notify_interval = 30 secs

namespace inbox {
  inbox = yes
  separator = /
  prefix =
  mailbox Drafts {
    special_use = \\Drafts
  }
  mailbox Sent {
    special_use = \\Sent
  }
  mailbox Trash {
    special_use = \\Trash
  }
  mailbox Junk {
    special_use = \\Junk
  }
  mailbox Archive {
    special_use = \\Archive
  }
}

service imap-login {
  inet_listener imap {
    address = 127.0.0.1
    port = $IMAP_PORT
  }
  inet_listener imaps {
    address = 127.0.0.1
    port = $IMAPS_PORT
    ssl = yes
  }
}
service stats {
  unix_listener stats-reader {
    user = $user
  }
  unix_listener stats-writer {
    user = $user
  }
}
EOF
}

start() {
    if running; then echo "already running from $(current_dir)" >&2; return 0; fi
    local dovecot dir
    dovecot="$(find_dovecot)"
    mkdir -p "$CACHE"
    dir="$(mktemp -d "${TMPDIR:-/tmp}/ravenglass-dovecot.XXXXXX")"
    configure "$dir"
    echo "$dir" >"$POINTER"
    "$dovecot" -c "$dir/dovecot.conf" </dev/null >/dev/null 2>&1
    for _ in $(seq 1 50); do
        if (exec 3<>"/dev/tcp/127.0.0.1/$IMAP_PORT") 2>/dev/null; then
            echo "started from $dir (IMAP STARTTLS $IMAP_PORT, IMAPS $IMAPS_PORT), log in $dir/dovecot.log" >&2
            return 0
        fi
        sleep 0.1
    done
    echo "dovecot did not start; see $dir/dovecot.log" >&2
    exit 1
}

stop() {
    local dir
    dir="$(current_dir)" || return 0
    if running; then
        "$(find_dovecot)" -c "$dir/dovecot.conf" stop 2>/dev/null || kill "$(cat "$dir/run/master.pid")"
        for _ in $(seq 1 50); do running || break; sleep 0.1; done
    fi
    case "$dir" in */ravenglass-dovecot.*) rm -rf "$dir" ;; esac
    rm -f "$POINTER"
}

case "${1:-}" in
    start) start ;;
    stop) stop ;;
    status) if running; then echo "running from $(current_dir)"; else echo "not running"; exit 1; fi ;;
    doveadm)
        shift
        dir="$(current_dir)" || { echo "not running" >&2; exit 1; }
        exec "$(find_doveadm)" -c "$dir/dovecot.conf" "$@"
        ;;
    *) echo "usage: $0 start|stop|status|doveadm …" >&2; exit 2 ;;
esac
